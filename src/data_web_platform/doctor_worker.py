"""Isolated Doctor jobs. Mutators can only write a newly reserved output.

The request file is generated by the platform's validated job queue, not an arbitrary
client command. Paths and structured options are nevertheless checked again at
execution time. Failed/partial copies are retained for review, never deleted.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import time
import traceback
from contextlib import contextmanager
from dataclasses import asdict
from pathlib import Path

from .datasets import dataset_fingerprint, inspect_dataset
from .doctor import DoctorRequest, run_check
from .paths import validate_output_path, validate_path


def emit(event: str, **fields):
    print("DWP_EVENT " + json.dumps({"event": event, **fields}, ensure_ascii=False,
                                    default=str), flush=True)


@contextmanager
def stage(name, timings):
    started = time.monotonic()
    emit("stage", name=name, status="running")
    try:
        yield
    except Exception:
        emit("stage", name=name, status="failed", seconds=time.monotonic() - started)
        raise
    else:
        timings[name] = time.monotonic() - started
        emit("stage", name=name, status="succeeded", seconds=timings[name])


def _validated_request(request):
    if not isinstance(request, dict) or request.get("kind") != "doctor":
        raise ValueError("无效的 Doctor 请求")
    roots = request.get("allowed_roots")
    sources = request.get("sources")
    # Explicit null is the OS-permission policy prepared by the server. Keep
    # old queued requests with explicit scopes readable; missing policy is bad.
    if "allowed_roots" not in request or (roots is not None and (
            not isinstance(roots, list) or not roots or not all(isinstance(p, str) for p in roots))):
        raise ValueError("缺少或无效的文件系统访问策略")
    if not isinstance(sources, list) or not sources or len(sources) > 100:
        raise ValueError("缺少数据集路径")
    if not isinstance(request.get("options"), dict):
        raise ValueError("Doctor 选项必须是结构化对象")
    # Pydantic rejects unknown fields/operations/checks/fixes and string booleans.
    parsed = DoctorRequest.model_validate({**request["options"],
        "operation": request.get("operation"), "dataset": request.get("dataset"),
        "datasets": sources if request.get("operation") == "merge-check" else [],
        "output": request.get("output"), "confirm": request.get("confirm", False)})
    if parsed.operation != "merge-check" and len(sources) != 1:
        raise ValueError("此操作只接受一个数据集")
    paths = [inspect_dataset(source, roots)[0] for source in sources]
    if len(set(paths)) != len(paths):
        raise ValueError("不能重复引用同一个数据集")
    if parsed.urdf:
        urdf = validate_path(parsed.urdf, roots)
        if not urdf.is_file():
            raise ValueError("URDF 必须是本地文件")
        parsed.urdf = str(urdf)
    return parsed, roots, paths


def _copy_for_mutation(source, destination, roots):
    destination = validate_output_path(destination, roots, [source])
    # Never preserve a link to production or a hardlink. Refuse symlinks even
    # when internal: following directory links risks recursion/TOCTOU surprises.
    if any(entry.is_symlink() for entry in source.rglob("*")):
        raise ValueError("修复/裁剪副本暂不接受含符号链接的数据集，请先提供普通文件副本")
    before = dataset_fingerprint(source)
    destination.parent.mkdir(parents=True, exist_ok=True)
    # Re-resolve after parent creation and reserve exclusively. copytree's
    # dirs_exist_ok is safe only after *this* mkdir succeeds.
    destination = validate_output_path(destination, roots, [source])
    destination.mkdir(mode=0o700, exist_ok=False)
    # Reserve before copying even the first metadata file. A partial copy may
    # look structurally complete, but it must never be manually registered.
    (destination / ".dwp-incomplete").write_text("Doctor fix has not passed validation.\n")
    shutil.copytree(source, destination, dirs_exist_ok=True, symlinks=False,
                    copy_function=shutil.copy2)
    if dataset_fingerprint(source) != before:
        raise ValueError("复制期间源数据发生变化；已保留未发布的副本，请检查后重试")
    return destination


def run_prepared(request: dict, *, workspace=None) -> int:
    """Run one prepared request, emit a result even for an adverse quality gate."""
    timings = {}
    with stage("preflight", timings):
        options, roots, sources = _validated_request(request)
    operation = options.operation
    output = None
    result = {"operation": operation, "dataset": request["dataset"],
              "source_paths": [str(path) for path in sources]}
    failed = False
    before = [dataset_fingerprint(source) for source in sources]
    if operation == "fix":
        with stage("copy", timings):
            output = _copy_for_mutation(sources[0], options.output, roots)
        result.update(path=str(output), destination=str(output), source_unchanged=True,
                      dry_run=options.dry_run)
    with stage(operation, timings):
        if operation == "check":
            report = run_check(sources[0], checks=options.checks,
                               max_episodes=options.max_episodes, urdf=options.urdf,
                               workspace=workspace)
            emit("check_report", report=report)
            result["report"] = report
            failures = {"FAIL", "WARN"} if options.fail_on == "warn" else {"FAIL"}
            failed = report.get("overall_severity", "PASS").upper() in failures
        elif operation == "score":
            from .doctor_compat import run_score
            result["report"] = run_score(sources[0],
                max_episodes=options.max_episodes, drop_threshold=options.drop_threshold,
                workspace=workspace)
        elif operation == "gate":
            from .doctor_compat import run_gate
            report = run_gate(sources[0], policy=options.policy,
                             custom_chunk_size=options.chunk_size, workspace=workspace)
            result["report"] = report
            failed = not report["passed"]
        elif operation == "merge-check":
            from lerobot_doctor.merge_check import check_merge_compatibility, validate_merged_dataset
            report = (validate_merged_dataset(sources[0]) if options.post_merge
                      else check_merge_compatibility(sources))
            result["report"] = asdict(report)
            failed = not report.compatible
        elif operation == "fix":
            from lerobot_doctor.fix import fix_dataset
            # Upstream backup uses a sibling path and is not an independent
            # dataset backup. Our exclusive copy is the only mutation target.
            report = fix_dataset(output, fixes=options.fixes, backup=False,
                                 dry_run=options.dry_run)
            result["report"] = asdict(report)
            failed = bool(report.errors)
        elif operation == "trim":
            from .trim import trim_dataset
            report = trim_dataset(sources[0], options.output, roots,
                threshold=options.threshold, min_active=options.min_active,
                keep_static=options.keep_static, dry_run=options.dry_run,
                defer_publication=True,
                progress=lambda index, total: emit("log", message=f"Trim episode {index + 1}/{total}"))
            result.update(report=report, source_unchanged=True, dry_run=options.dry_run,
                          preview_only=options.dry_run)
            if not options.dry_run:
                output = Path(report["path"])
                result.update(path=str(output), destination=str(output))
    if output:
        with stage("validate", timings):
            from letools.validation import validate_dataset
            validation = validate_dataset(output, deep=True)
            result["validation"] = asdict(validation)
            emit("validation", report=result["validation"])
            failed = failed or not validation.valid
    after = [dataset_fingerprint(source) for source in sources]
    if before != after:
        result.update(source_unchanged=False)
        emit("result", result={**result, "timings": timings, "passed": False})
        raise ValueError("任务期间源数据发生变化；报告/副本未通过稳定性检查")
    if output and not failed:
        # Only release after the upstream result, deep output validation and
        # unchanged-source checks all succeed. Any exception retains the marker.
        (output / ".dwp-incomplete").unlink()
    result.update(timings=timings, passed=not failed)
    emit("result", result=result)
    if failed:
        emit("error", message="Doctor 检查/质量门槛或副本验证未通过；请查看完整报告。原数据未修改。")
    return 1 if failed else 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("request_file", nargs="?")
    parser.add_argument("--request-json")
    args = parser.parse_args(argv)
    try:
        if bool(args.request_file) == bool(args.request_json):
            raise ValueError("必须且只能指定请求文件或 --request-json")
        request = json.loads(args.request_json if args.request_json else Path(args.request_file).read_text())
        try:
            os.nice(10)
        except OSError:
            pass
        return run_prepared(request, workspace=Path(args.request_file).parent if args.request_file else None)
    except Exception as error:
        emit("error", message=str(error))
        traceback.print_exc()
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
